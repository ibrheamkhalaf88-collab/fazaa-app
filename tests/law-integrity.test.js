test("every article has a topic, a number and a fingerprint; every law names its source and court", () => {
  for (const a of Object.values(ARTICLES)) {
    assert.ok(a.topic.length > 3, a.id);
    assert.match(String(a.number), /^\d{1,4}$/, a.id);
    if (a.url) assert.match(a.url, /^https:\/\//, a.id);
  }
  for (const law of LAWS) {
    assert.ok(law.source, law.key);
    assert.ok(["sharia", "nizami", "general"].includes(law.court), law.key);
    assert.ok(law.regions.length > 0, law.key);
  }
  assert.deepEqual(
    Object.keys(FINGERPRINTS).sort(),
    Object.keys(ARTICLES).sort(),
    "fingerprint missing for an article",
  );
});

test("damaged PDF characters, page numbers and chapter titles never reach the corpus", () => {
  for (const a of Object.values(ARTICLES)) {
    assert.ok(!a.text.includes("�"), `${a.id} has a damaged character`);
    // chapter titles were printed between the articles of the family-rights PDF (other laws cite chapters by name)
    if (a.id.startsWith("gz:"))
      assert.ok(!/(?:^|\s)(?:الباب|الفصل|الكتاب)\s/.test(a.text), `${a.id} carries a chapter title`);
    assert.ok(!/الرقم المرجعي|ديوان الفتوى|الوقائع الفلسطينية/.test(a.text), `${a.id} carries a page footer`);
    assert.ok(!/\s\d{1,2}$/.test(a.text) && !/^\d{1,2}\s/.test(a.text), `${a.id} carries a page number`);
  }
});

