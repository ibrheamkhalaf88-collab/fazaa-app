/**
 * Runs the assistant evaluation set (tests/fixtures/assistant-scenarios.js) on the OFFLINE path and
 * prints measured rates. No network, no model: this measures the app's own behaviour (the reply she
 * gets whenever the AI is off or fails, and every danger reply). Model quality is NOT measured here.
 *
 *   node scripts/assistant-eval.mjs [--transcript docs/evidence/assistant-eval.txt]
 */
import { writeFileSync } from "node:fs";
import { createAnswerer } from "../src/ai/answerer.js";
import { CONVERSATIONS, LEGAL, SAFETY } from "../tests/fixtures/assistant-scenarios.js";
import { checkAnswer, sentences } from "../tests/fixtures/check.js";

const NUMBERS = { police: "100", ambulance: "101" };
const make = (numbers = NUMBERS) =>
  createAnswerer({ emergencyNumbers: () => numbers, available: () => ({ lawyer: true, contacts: true }) });

const out = [];
const show = (a) => {
  if (!a) return "   [no reply: not-covered screen]";
  const lines = [`   [${a.kind || "law"}${a.sos ? " sos" : ""}${a.cites?.length ? ` cites:${a.cites}` : ""}${a.related?.length ? ` texts:${a.related}` : ""}]`, `   ${a.lead}`];
  for (const o of a.options || a.steps || []) lines.push(`   • ${o}`);
  for (const s of a.scope || []) lines.push(`   (${s})`);
  if (a.ask || a.safetyAsk) lines.push(`   ? ${a.ask || a.safetyAsk}`);
  return lines.join("\n");
};

const stats = { turns: 0, ms: 0 };
async function run(a, say, country = "ps-wb") {
  const t0 = performance.now();
  const r = await a.answer(say, { country });
  stats.ms += performance.now() - t0;
  stats.turns++;
  out.push(`SHE: ${say}`, show(r));
  return r;
}

const result = {};
const tally = (cat, ok) => {
  result[cat] ??= { pass: 0, total: 0 };
  result[cat].total++;
  if (ok) result[cat].pass++;
};

let repeated = 0;
let sentencesTotal = 0;
let askedTwice = 0;
let asksTotal = 0;
let contextChecks = 0;
let contextPass = 0;

for (const c of CONVERSATIONS) {
  out.push(`\n=== ${c.id}`);
  const a = make();
  const answers = [];
  let ok = true;
  for (const turn of c.turns) {
    const r = await run(a, turn.say, turn.country);
    answers.push(r);
    const p = checkAnswer(r, turn.expect, a.memory);
    if (Object.keys(turn.expect).length) {
      contextChecks++;
      if (!p.length) contextPass++;
    }
    if (p.length) (ok = false), out.push(`   !! ${p.join("; ")}`);
  }
  if (c.check && c.check(answers, a.memory) !== true) ok = false;
  const all = answers.flatMap(sentences);
  sentencesTotal += all.length;
  repeated += all.filter((s, i) => all.indexOf(s) !== i).length;
  const asks = answers.map((r) => r?.ask).filter(Boolean);
  asksTotal += asks.length;
  askedTwice += asks.filter((s, i) => asks.indexOf(s) !== i).length;
  tally("conversations", ok);
}

for (const l of LEGAL) {
  out.push(`\n=== ${l.id}`);
  const a = make();
  let ok;
  if (l.turns) {
    await run(a, l.turns[0], l.country);
    ok = l.expect2(await run(a, l.turns[1], l.country)) === true;
  } else {
    const p = checkAnswer(await run(a, l.say, l.country), l.expect);
    ok = !p.length;
    if (!ok) out.push(`   !! ${p.join("; ")}`);
  }
  tally("legal", ok);
}

for (const s of SAFETY) {
  out.push(`\n=== ${s.id}`);
  const a = make(s.numbers || NUMBERS);
  let ok = true;
  for (const [i, say] of s.turns.entries()) {
    const p = checkAnswer(await run(a, say), s.expect[i] || {});
    if (p.length) (ok = false), out.push(`   !! ${p.join("; ")}`);
  }
  tally("safety", ok);
}

const pct = (n, d) => (d ? `${((100 * n) / d).toFixed(1)}%` : "n/a");
console.log("Assistant evaluation (offline path, synthetic data, no model)");
for (const [cat, { pass, total }] of Object.entries(result)) console.log(`  ${cat.padEnd(14)} ${pass}/${total} scenarios pass (${pct(pass, total)})`);
console.log(`  context checks  ${contextPass}/${contextChecks} turns with an expectation met (${pct(contextPass, contextChecks)})`);
console.log(`  repetition      ${repeated}/${sentencesTotal} reply sentences repeated within a conversation (${pct(repeated, sentencesTotal)})`);
console.log(`  same question   ${askedTwice}/${asksTotal} questions asked twice within a conversation (${pct(askedTwice, asksTotal)})`);
console.log(`  latency         ${(stats.ms / stats.turns).toFixed(2)} ms per turn on this machine (${stats.turns} turns)`);

const i = process.argv.indexOf("--transcript");
if (i > 0) {
  writeFileSync(process.argv[i + 1], `# Generated by scripts/assistant-eval.mjs (offline path, synthetic data)\n${out.join("\n")}\n`, "utf8");
  console.log(`  transcript      ${process.argv[i + 1]}`);
}
