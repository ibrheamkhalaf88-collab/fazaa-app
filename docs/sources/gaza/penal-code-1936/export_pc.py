"""pc_final.json -> src/data/law/gaza/nizami/penal-code-1936.js (same shape as the other law files)."""
import json, sys

A = json.load(open("pc_final.json", encoding="utf-8"))
out_path = sys.argv[1]
BIS = {"36 مكررة (أ)": "36-1", "66 مكررة (أ)": "66-1", "109 مكررة (أ)": "109-1", "109 مكررة (ب)": "109-2",
       "285 أ": "285-1", "388 مكررة (أ)": "388-1"}


def js(s):
    return json.dumps(s, ensure_ascii=False)


open_notes = [f"art. {a['number']}: {o}" for a in A for o in a["open"]]
head = f'''/**
 * قانون العقوبات رقم (74) لسنة 1936، بتعديلاته المنشورة في ملحق ملف المحامي (1937 حتى 1984).
 * تنظر فيه المحاكم النظامية والنيابة العامة في قطاع غزة.
 *
 * SOURCE: the PDF the owner's lawyer approved (Desktop «العقوبات ١٩٣٦ .pdf», 208 pages, 2026-11-23): the 1936 text
 * (pages 1-171) followed by an appendix of amending laws. Text taken from the PDF text layer, rebuilt from glyph
 * positions (lam-alef ligatures and tanween restored), checked against the page images on samples.
 * Amendments applied here, each recorded in `amended`:
 *   37/1937 (art. 105); 59/1939 (5, 33, 42, 59, 60, 226); 21/1944 (66 bis A, 315); 41/1944 (5, 106-109,
 *   109 bis A and B, 113, 195, 258, 385); probation law 42/1944 (37; art. 46 repealed, so it is left out);
 *   57/1946 (3, 36 bis A, 42, 110-112, 131, 164, 193, 345, 388, 388 bis A); 1/1947 (181);
 *   Gaza military orders 150/1968 (311), 742/1982 (285 A), 852/1984 (270).
 * NOT applied, for the lawyer: {"; ".join(open_notes)}.
 * Order 150/1968 also adds an «art. 44 A» to «the Egyptian penal code»; it does not name this law, so it is left out.
 * The table of art. 42 is not printed in the PDF. Bis articles have ids like «pc:66-1»; their topics for
 * 109 bis A/B are ours (the amending law gives no title). Fines are in Palestine pounds (جنيه) as printed.
 * Amendments after 1984 (if any) are not in the lawyer's file.
 * Generated by the scratch pipeline; do NOT edit article text by hand. tests/law-integrity.test.js fingerprints it.
 */

/** @typedef {{import("../../types.js").Article}} Article */

export const PENAL_CODE_NAME = "قانون العقوبات رقم (74) لسنة 1936 وتعديلاته";

/** @type {{Article[]}} */
export const PENAL_CODE = [
'''
body = []
for a in A:
    n = a["number"]
    idn = BIS.get(n, n)
    assert idn.replace("-", "").isdigit(), n
    body.append(
        "  {\n"
        f"    id: {js('pc:' + idn)},\n"
        f"    number: {js(n)},\n"
        f"    topic: {js(a['topic'])},\n"
        '    url: "",\n'
        f"    amended: {js(a['amended'])},\n"
        f"    text: {js(a['text'])},\n"
        "  },\n"
    )
open(out_path, "w", encoding="utf-8", newline="\n").write(head.replace("{{", "{").replace("}}", "}") + "".join(body) + "];\n")
print("wrote", len(A), "articles")
